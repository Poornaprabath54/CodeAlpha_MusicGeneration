class CodingAssistant:
    def looks_like_code_request(self, text):
        t = text.lower()
        languages = any(k in t for k in LANG_ALIASES)
        verbs = any(k in t for k in ['write', 'create', 'generate', 'program', 'code', 'script', 'debug', 'convert', 'implement', 'algorithm'])
        return languages and verbs

    def detect_language(self, text):
        t = text.lower()
        for key in sorted(LANG_ALIASES, key=len, reverse=True):
            if re.search(r'(?<![a-z0-9+#])' + re.escape(key) + r'(?![a-z0-9])', t):
                return LANG_ALIASES[key]
        return 'python'

    def generate(self, text):
        lang = self.detect_language(text)
        task = text.lower()
        if Config.GEMINI_API_KEY:
            try:
                url=f'https://generativelanguage.googleapis.com/v1beta/models/{Config.GEMINI_MODEL}:generateContent'
                prompt=(f'You are a senior programming tutor. Return concise Markdown with a title, explanation, complete working {lang} code, sample output, and time/space complexity. User request: {text}')
                r=requests.post(url,params={'key':Config.GEMINI_API_KEY},json={'contents':[{'parts':[{'text':prompt}]}]},timeout=30)
                if r.ok:
                    out=r.json()['candidates'][0]['content']['parts'][0]['text']
                    code_match=re.search(r'```(?:[\w+#-]+)?\n(.*?)```',out,re.S)
                    code=code_match.group(1).strip() if code_match else out
                    return {'language':lang,'title':f'Gemini-generated {lang.title()} solution','code':code,'explanation':out,'complexity':self._complexity(task)}
            except Exception:
                pass
        code, title = self._template(lang, task)
        return {'language': lang, 'title': title, 'code': code, 'explanation': 'Generated by the local CodeAlpha coding assistant. Add GEMINI_API_KEY to .env for richer Gemini-powered generation.', 'complexity': self._complexity(task)}

    def _complexity(self, task):
        if 'binary search' in task: return 'Time: O(log n) | Space: O(1)'
        if 'linear search' in task: return 'Time: O(n) | Space: O(1)'
        if 'bubble sort' in task: return 'Time: O(n²) average/worst | Space: O(1)'
        return 'Complexity depends on the requested algorithm.'

